/**
 * SOC L1 track files: track.yaml (config-only gating), content/coverage/soc.yaml (skills coverage) and
 * <lesson>.cards.yaml (flashcards). Node-only loaders for the content gate and the card generator.
 */
import fs from "node:fs";
import path from "node:path";
import { parse as parseYaml } from "yaml";
import { z } from "zod";
import type { LessonCard } from "./soc-lesson-lint";

export const SOC_L1_DIR = "content/tracks/soc/l1";

export const trackConfigSchema = z.object({
  id: z.string(),
  title: z.string(),
  enabled: z.boolean(),
  min_core_rank: z.number().int().min(0).max(5),
  lesson_world: z.object({ organisation: z.string(), domain: z.string(), external_range: z.string(), internal_range: z.string() }),
  modules: z.array(z.object({ id: z.string(), key: z.string(), order: z.number().int(), title: z.string() })).min(1),
});
export type TrackConfig = z.infer<typeof trackConfigSchema>;

export const socCoverageSchema = z.object({
  version: z.literal(1),
  skills: z.array(
    z.object({
      id: z.string().regex(/^soc_[a-z_]+$/),
      planned: z.string(),
      lessons: z.array(z.string()),
      practice: z.array(z.string()),
      gap: z.string().nullable(),
    }),
  ),
});
export type SocCoverage = z.infer<typeof socCoverageSchema>;

export const cardsFileSchema = z.object({
  lesson: z.string(),
  cards: z
    .array(z.object({ id: z.string().regex(/^fc-[a-z0-9-]+-\d{2}$/), front: z.string().min(10), back: z.string().min(10) }))
    .min(1),
});

export function loadTrackConfig(dir = SOC_L1_DIR): TrackConfig {
  return trackConfigSchema.parse(parseYaml(fs.readFileSync(path.join(dir, "track.yaml"), "utf8")));
}

export function loadSocCoverage(file = "content/coverage/soc.yaml"): SocCoverage {
  return socCoverageSchema.parse(parseYaml(fs.readFileSync(file, "utf8")));
}

/** Cards next to a lesson file, or null when the lesson has none. */
export function loadLessonCards(lessonFile: string): { lesson: string; cards: LessonCard[] } | null {
  const file = lessonFile.replace(/\.mdx$/, ".cards.yaml");
  if (!fs.existsSync(file)) return null;
  const parsed = cardsFileSchema.safeParse(parseYaml(fs.readFileSync(file, "utf8")));
  if (!parsed.success) throw new Error(`${file}: ${parsed.error.issues.map((i) => `${i.path.join(".")}: ${i.message}`).join("; ")}`);
  return parsed.data;
}

/** Coverage file ↔ lessons, both directions; practice targets must resolve; skills must exist. */
export function socCoverageErrors(
  coverage: SocCoverage,
  lessons: Array<{ id: string; skills?: string[] }>,
  skillIds: Set<string>,
  practiceError: (target: string) => string | null,
): string[] {
  const errors: string[] = [];
  const byId = new Map(lessons.map((l) => [l.id, l]));
  const listed = new Set(coverage.skills.map((s) => s.id));
  for (const s of skillIds) if (!listed.has(s)) errors.push(`coverage/soc.yaml: skill ${s} is missing`);
  for (const s of coverage.skills) {
    if (!skillIds.has(s.id)) errors.push(`coverage/soc.yaml: unknown skill ${s.id}`);
    for (const id of s.lessons) {
      const l = byId.get(id);
      if (!l) errors.push(`coverage/soc.yaml: ${s.id} lists unknown lesson ${id}`);
      else if (!l.skills?.includes(s.id)) errors.push(`coverage/soc.yaml: ${s.id} lists ${id}, which does not teach it`);
    }
    for (const t of s.practice) {
      const problem = practiceError(t);
      if (problem) errors.push(`coverage/soc.yaml: ${s.id} practice ${t}: ${problem}`);
    }
    if (!s.practice.length && !s.gap) errors.push(`coverage/soc.yaml: ${s.id} has no practice and no stated gap`);
  }
  for (const l of lessons) {
    for (const sk of l.skills ?? []) {
      if (!coverage.skills.find((s) => s.id === sk)?.lessons.includes(l.id)) errors.push(`coverage/soc.yaml: ${sk} does not list ${l.id}`);
    }
  }
  return errors;
}

export type TrackCardEntry = { lessonId: string; rank: number; cards: LessonCard[] };

/** Source of lib/review/track-cards.generated.ts (the review scheduler reads cards synchronously, no fs at runtime). */
export function renderTrackCardsModule(entries: TrackCardEntry[]): string {
  const cards = entries.flatMap((e) =>
    e.cards.map((c) => ({ id: c.id, lessonId: e.lessonId, rank: e.rank, category: "soc" as const, front: c.front, back: c.back })),
  );
  return [
    "// GENERATED by `npm run soc:curriculum -- cards` from content/tracks/**/*.cards.yaml. Do not edit.",
    "// check:content fails when this file is out of date.",
    'import type { FlashCard } from "./flashcards";',
    "",
    `export const TRACK_FLASHCARDS: FlashCard[] = ${JSON.stringify(cards, null, 2)};`,
    "",
  ].join("\n");
}
